  function layout(text) {
    let x = 0; const out = [];
    for (const ch of String(text).toUpperCase()) {
      if (ch === ' ') { x += SPACE; continue; }
      const g = G[ch]; if (!g) continue;
      out.push({ ch, x, g }); x += g.w + TRACK;
    }
    return { width: Math.max(0, x - TRACK), glyphs: out };
  }


"""Embed ../src/dash/*.webp into sites/dashboard/index.html as window.PEP_VIALS (data URIs). Re-run after dashvials.py."""
import base64, json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC, PAGE = ROOT / 'brand/src/dash', ROOT / 'sites/dashboard/index.html'
m = {p.stem: 'data:image/webp;base64,' + base64.b64encode(p.read_bytes()).decode() for p in sorted(SRC.glob('*.webp'))}
block = '<script id="pep-vials">/* VIALS: generated by brand/tools/dash_embed.py */window.PEP_VIALS=' + json.dumps(m, separators=(',', ':')) + ';</script>\n'
s = PAGE.read_text()
s = re.sub(r'<script id="pep-vials">.*?</script>\n', '', s, flags=re.S)
i = s.index('<script>\n(function(){')
PAGE.write_text(s[:i] + block + s[i:])
print(len(m), 'vials,', PAGE.stat().st_size // 1024, 'KB page')

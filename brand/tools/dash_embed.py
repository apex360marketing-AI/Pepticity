"""Embed the dashboard bottles into sites/dashboard/index.html as window.PEP_VIALS (data URIs).

Bottle swap point: brand/vials-final/<slug>-front.webp (the final bottles) wins whenever it exists;
otherwise the temporary art in brand/src/dash/<slug>.webp is used. Final bottles are scaled to 380 px tall
so the page stays light. Re-run after dashvials.py or whenever new files land in brand/vials-final/.
"""
import base64, io, json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC, FINAL, PAGE = ROOT / 'brand/src/dash', ROOT / 'brand/vials-final', ROOT / 'sites/dashboard/index.html'
H = 380


def data_uri(p):
    if p.parent == FINAL:
        from PIL import Image
        im = Image.open(p).convert('RGBA')
        if im.height > H:
            im = im.resize((round(im.width * H / im.height), H), Image.LANCZOS)
        buf = io.BytesIO(); im.save(buf, 'WEBP', quality=86, method=6); raw = buf.getvalue()
    else:
        raw = p.read_bytes()
    return 'data:image/webp;base64,' + base64.b64encode(raw).decode()


files = {p.stem: p for p in sorted(SRC.glob('*.webp'))}
used_final = 0
if FINAL.is_dir():
    for p in sorted(FINAL.glob('*-front.webp')):
        files[p.stem[:-len('-front')]] = p; used_final += 1
m = {k: data_uri(p) for k, p in sorted(files.items())}
block = '<script id="pep-vials">/* VIALS: generated by brand/tools/dash_embed.py */window.PEP_VIALS=' + json.dumps(m, separators=(',', ':')) + ';</script>\n'
s = PAGE.read_text()
s = re.sub(r'<script id="pep-vials">.*?</script>\n', '', s, flags=re.S)
i = s.index('<script>\n(function(){')
PAGE.write_text(s[:i] + block + s[i:])
print(len(m), 'vials (', used_final, 'final ),', PAGE.stat().st_size // 1024, 'KB page')
